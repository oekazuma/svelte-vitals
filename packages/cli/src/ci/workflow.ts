import type { InstallStepPlan } from './install-step.js';

export const WORKFLOW_PATH = '.github/workflows/svelte-vitals.yml';

// Kept in lockstep with the pin this repo's own workflows use (.github/workflows/ci.yml,
// release.yml, deploy-docs.yml) — bump both together when actions/checkout cuts a new release.
// test/ci/lockstep.test.ts asserts this against .github/workflows/ci.yml directly.
export const CHECKOUT_SHA = '3d3c42e5aac5ba805825da76410c181273ba90b1';
export const CHECKOUT_VERSION = 'v7.0.1';

// Same lockstep, against .github/workflows/setup-node/action.yml (test/ci/lockstep.test.ts).
export const PNPM_SETUP_SHA = 'fa36a5ef7dcdefc3a7cb25655c122e00cf6e636e';
export const PNPM_SETUP_VERSION = 'v3.1.2';

interface WorkflowPlan {
  status: 'created' | 'exists' | 'updated';
  content?: string;
}

/**
 * Decide what to do with the generated workflow file, mirroring the `install` wizard's
 * WriteStatus convention: no existing file → 'created'; an existing file with no
 * --force → 'exists' (left untouched, idempotent re-runs); --force → 'updated'.
 * Content generation is the caller's job (`gunshi/ci.ts`) — this function only decides.
 */
export function planWorkflowWrite(existing: string | undefined, force: boolean): WorkflowPlan {
  if (existing === undefined) return { status: 'created' };
  if (!force) return { status: 'exists' };
  return { status: 'updated' };
}

/**
 * Build the short GitHub Actions workflow that calls the `svelte-vitals-action` GitHub
 * Action (issue #154 — replaces the old ~60-line inline template; see
 * plans/020-reusable-github-action.md). The action itself owns annotations, the job
 * summary, the sticky PR comment, and the gate — `ci install` only scaffolds the call,
 * pinned to a commit SHA with a same-line version comment. `actions/checkout` is pinned
 * the same way, matching this repo's own `actions/checkout@<sha> # vX.Y.Z` convention
 * (.github/workflows/ci.yml etc.) rather than a floating tag. `svelte-vitals-action` lives
 * in its own dedicated repository (not a subdirectory of this monorepo), so its tags are
 * plain `vX.Y.Z` — Renovate's github-actions manager parses that natively, no special
 * comment format needed.
 *
 * The action analyzes with the svelte-vitals in the project's node_modules, so an install step
 * sits between checkout and the action call. It is live only for the shapes known to work on a
 * first run (npm, and pnpm 11+ through the pinned setup action); any other project gets the step
 * commented out. Lifecycle scripts stay off: analysis needs none, and they would run dependency
 * code in a job granted pull-requests: write.
 */
export function buildWorkflowYaml(opts: {
  actionSha: string;
  actionVersion: string;
  installStep: InstallStepPlan;
}): string {
  const { actionSha, actionVersion, installStep } = opts;
  return [
    '# Generated by svelte-vitals (`ci install` or `install --client ci-workflow`).',
    '# Re-run with --force to regenerate.',
    'name: svelte-vitals',
    '',
    'on:',
    '  pull_request:',
    '',
    'permissions:',
    '  contents: read',
    '  pull-requests: write',
    '',
    'jobs:',
    '  svelte-vitals:',
    '    runs-on: ubuntu-latest',
    '    steps:',
    `      - uses: actions/checkout@${CHECKOUT_SHA} # ${CHECKOUT_VERSION}`,
    '        with:',
    '          fetch-depth: 0',
    '          persist-credentials: false',
    ...installStepLines(installStep),
    `      - uses: oekazuma/svelte-vitals-action@${actionSha} # v${actionVersion}`,
    '        with:',
    '          diff: origin/${{ github.base_ref }}',
    '          baseline: origin/${{ github.base_ref }}',
    ''
  ].join('\n');
}

function installStepLines(plan: InstallStepPlan): string[] {
  switch (plan.kind) {
    case 'npm':
      return ['      - run: npm ci --ignore-scripts'];
    case 'pnpm':
      return [
        `      - uses: pnpm/setup@${PNPM_SETUP_SHA} # ${PNPM_SETUP_VERSION}`,
        '        with:',
        '          install: false',
        '      - run: pnpm install --frozen-lockfile --ignore-scripts'
      ];
    case 'manual':
      return [
        '      # The action analyzes with the svelte-vitals installed in this project. Set up your package',
        '      # manager and install dependencies here; without an install it uses its bundled analyzer',
        '      # and says so in a warning.',
        `      # - run: ${plan.command}`
      ];
  }
}

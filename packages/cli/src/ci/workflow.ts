export const SETUP_NODE_SHA = '949feb2413d6458794dcd2491c4babbbce0c15c1';
export const SETUP_NODE_VERSION = 'v7.1.0';

interface WorkflowPlan {
  status: 'created' | 'exists' | 'updated';
  content?: string;
}

/**
 * Decide what to do with the generated workflow file, mirroring the `install` wizard's
 * WriteStatus convention: no existing file → 'created'; an existing file with no
 * --force → 'exists' (left untouched, idempotent re-runs); --force → 'updated'.
 * Content generation is the caller's job (`gunshi/ci.ts`) — this function only decides.
 */
export function planWorkflowWrite(existing: string | undefined, force: boolean): WorkflowPlan {
  if (existing === undefined) return { status: 'created' };
  if (!force) return { status: 'exists' };
  return { status: 'updated' };
}

/**
 * The workflow runs the svelte-vitals installed in the project (`./node_modules/.bin`, so a pull
 * request cannot make it fetch anything from a registry) with the github reporter, which writes the
 * annotations and the job summary itself. Every action is pinned to a commit SHA with a same-line
 * `# vX.Y.Z` comment, the convention this repo's own workflows follow.
 *
 * The install step is live only for the shapes known to work on a first run (npm, and pnpm 11+
 * through the pinned setup action); any other project gets it commented out. Lifecycle scripts stay
 * off: analysis needs none, and they would run dependency code from the pull request. The base ref
 * goes through `env:` rather than into the command, so no expression is interpolated into a shell.
 * `appPath` (POSIX, relative to the repository root) is the project to analyze in a monorepo.
 */
export function buildWorkflowYaml(opts: { installStep: InstallStepPlan; appPath?: string }): string {
  const { installStep, appPath } = opts;
  const target = appPath === undefined ? '' : ` '${appPath.replaceAll("'", "'\\''")}'`;
  return [
    '# Generated by svelte-vitals (`ci install` or `install --client ci-workflow`).',
    '# Re-run with --force to regenerate.',
    'name: svelte-vitals',
    '',
    'on:',
    '  pull_request:',
    '',
    'permissions:',
    '  contents: read',
    '',
    'jobs:',
    '  svelte-vitals:',
    '    runs-on: ubuntu-latest',
    '    steps:',
    `      - uses: actions/checkout@${CHECKOUT_SHA} # ${CHECKOUT_VERSION}`,
    '        with:',
    '          fetch-depth: 0',
    '          persist-credentials: false',
    ...installStepLines(installStep),
    `      - run: ./node_modules/.bin/svelte-vitals${target} --reporter github --diff "origin/$BASE_REF" --baseline "origin/$BASE_REF"`,
    '        env:',
    '          BASE_REF: ${{ github.base_ref }}',
    ''
  ].join('\n');
}

function installStepLines(plan: InstallStepPlan): string[] {
  switch (plan.kind) {
    case 'npm':
      return [
        `      - uses: actions/setup-node@${SETUP_NODE_SHA} # ${SETUP_NODE_VERSION}`,
        '        with:',
        '          node-version: 24',
        '      - run: npm ci --ignore-scripts'
      ];
    case 'pnpm':
      return [
        `      - uses: pnpm/setup@${PNPM_SETUP_SHA} # ${PNPM_SETUP_VERSION}`,
        '        with:',
        '          install: false',
        '          runtime: node',
        '      - run: pnpm install --frozen-lockfile --ignore-scripts'
      ];
    case 'manual':
      return [
        '      # Set up Node.js 24.16.0 or newer and your package manager, then install dependencies.',
        '      # Without an install the next step fails: it runs the svelte-vitals in node_modules.',
        `      # - run: ${plan.command}`
      ];
  }
}

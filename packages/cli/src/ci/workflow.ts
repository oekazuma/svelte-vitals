import type { InstallStepPlan } from './install-step.js';

export const WORKFLOW_PATH = '.github/workflows/svelte-vitals.yml';

// Kept in lockstep with the pin this repo's own workflows use (.github/workflows/ci.yml,
// release.yml, deploy-docs.yml) — bump both together when actions/checkout cuts a new release.
// test/ci/lockstep.test.ts asserts this against .github/workflows/ci.yml directly.
export const CHECKOUT_SHA = '3d3c42e5aac5ba805825da76410c181273ba90b1';
export const CHECKOUT_VERSION = 'v7.0.1';

// Same lockstep, against .github/workflows/setup-node/action.yml (test/ci/lockstep.test.ts).
export const PNPM_SETUP_SHA = '731dfb6463bbd11c11fd0ee11fe00ed0e36d48a1';
export const PNPM_SETUP_VERSION = 'v3.2.0';

// No counterpart in this repo's own workflows, so no lockstep test; Renovate's workflow.ts manager keeps it fresh.
export const SETUP_NODE_SHA = '949feb2413d6458794dcd2491c4babbbce0c15c1';
export const SETUP_NODE_VERSION = 'v7.1.0';

interface WorkflowPlan {
  status: 'created' | 'exists' | 'updated';
  content?: string;
}

/**
 * Decide what to do with the generated workflow file, mirroring the `install` wizard's
 * WriteStatus convention: no existing file → 'created'; an existing file with no
 * --force → 'exists' (left untouched, idempotent re-runs); --force → 'updated'.
 * Content generation is the caller's job (`gunshi/ci.ts`) — this function only decides.
 */
export function planWorkflowWrite(existing: string | undefined, force: boolean): WorkflowPlan {
  if (existing === undefined) return { status: 'created' };
  if (!force) return { status: 'exists' };
  return { status: 'updated' };
}

// `--no` makes npx refuse rather than download when the package is missing, and `--` stops npm 11
// from reading the step's flags as its own config (`--diff` is one). The manual shapes have no
// measured runner form, so they call the bin directly.
const RUNNERS = {
  npm: 'npx --no -- svelte-vitals',
  pnpm: 'pnpm exec svelte-vitals',
  manual: './node_modules/.bin/svelte-vitals'
};

/**
 * The workflow runs the svelte-vitals the project installed, with the github reporter, which writes
 * the annotations and the job summary itself. Every action is pinned to a commit SHA with a same-line
 * `# vX.Y.Z` comment, the convention this repo's own workflows follow.
 *
 * The install step is live only for the shapes known to work on a first run (npm, and pnpm 11+
 * through the pinned setup action); any other project gets it commented out. Lifecycle scripts stay
 * off: analysis needs none, and they would run dependency code from the pull request. The base ref
 * goes through `env:` rather than into the command, so no expression is interpolated into a shell.
 * `appPath` (POSIX, relative to the repository root) is the project to analyze in a monorepo.
 */
export function buildWorkflowYaml(opts: { installStep: InstallStepPlan; appPath?: string }): string {
  const { installStep, appPath } = opts;
  // A one-segment path can equal a subcommand name (`docs`, `ci`, ...), which the CLI dispatches on.
  const arg = appPath === undefined || appPath.includes('/') || appPath.startsWith('.') ? appPath : `./${appPath}`;
  const target = arg === undefined ? '' : ` '${arg.replaceAll("'", "'\\''")}'`;
  const run = `${RUNNERS[installStep.kind]}${target} --reporter github --diff "origin/$BASE_REF" --baseline "origin/$BASE_REF"`;
  // In a plain YAML scalar `: ` is invalid and ` #` starts a comment, so any other path is quoted.
  const safe = appPath === undefined || /^[\w ./@+'-]*$/.test(appPath);
  return [
    '# Generated by svelte-vitals (`ci install` or `install --client ci-workflow`).',
    '# Re-run with --force to regenerate.',
    'name: svelte-vitals',
    '',
    'on:',
    '  pull_request:',
    '',
    'permissions:',
    '  contents: read',
    '',
    'jobs:',
    '  svelte-vitals:',
    '    runs-on: ubuntu-latest',
    '    steps:',
    `      - uses: actions/checkout@${CHECKOUT_SHA} # ${CHECKOUT_VERSION}`,
    '        with:',
    '          fetch-depth: 0',
    '          persist-credentials: false',
    ...installStepLines(installStep),
    `      - run: ${safe ? run : JSON.stringify(run)}`,
    '        env:',
    '          BASE_REF: ${{ github.base_ref }}',
    // pnpm 11+ otherwise installs before `exec` when node_modules is missing or stale, and that
    // install runs the project's own lifecycle scripts.
    ...(installStep.kind === 'pnpm' ? ['          pnpm_config_verify_deps_before_run: error'] : []),
    ''
  ].join('\n');
}

function installStepLines(plan: InstallStepPlan): string[] {
  switch (plan.kind) {
    case 'npm':
      return [
        `      - uses: actions/setup-node@${SETUP_NODE_SHA} # ${SETUP_NODE_VERSION}`,
        '        with:',
        '          node-version: 24',
        '      - run: npm ci --ignore-scripts'
      ];
    case 'pnpm':
      return [
        `      - uses: pnpm/setup@${PNPM_SETUP_SHA} # ${PNPM_SETUP_VERSION}`,
        '        with:',
        '          install: false',
        '          runtime: node',
        '      - run: pnpm install --frozen-lockfile --ignore-scripts'
      ];
    case 'manual':
      return [
        '      # Set up Node.js 24.16.0 or newer and your package manager, then install dependencies.',
        '      # Without an install the next step fails: it runs the svelte-vitals in node_modules.',
        `      # - run: ${plan.command}`
      ];
  }
}

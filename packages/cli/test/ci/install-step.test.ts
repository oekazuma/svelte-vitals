import { describe, it, expect } from 'vitest';
import { planInstallStep } from '../../src/ci/install-step.js';

function io(files: Record<string, string>) {
  return { cwd: '/proj', readFile: (p: string) => files[p] };
}

const PNPM_COMMAND = 'pnpm install --frozen-lockfile --ignore-scripts';
const PNPM_UNDECLARED =
  'the pinned pnpm setup action needs the pnpm version from "packageManager" or "devEngines.packageManager" in package.json';

function pnpmProject(pkg: unknown) {
  return io({ '/proj/pnpm-lock.yaml': '', '/proj/package.json': JSON.stringify(pkg) });
}

describe('planInstallStep', () => {
  it('writes a live npm step for package-lock.json', () => {
    expect(planInstallStep(io({ '/proj/package-lock.json': '{}' }))).toEqual({ kind: 'npm' });
  });

  it('writes a live pnpm step when pnpm 11 or newer is declared', () => {
    expect(planInstallStep(pnpmProject({ packageManager: 'pnpm@11.2.0' }))).toEqual({ kind: 'pnpm' });
  });

  it('falls back to manual when pnpm 10 or older is declared', () => {
    expect(planInstallStep(pnpmProject({ packageManager: 'pnpm@9.15.0' }))).toEqual({
      kind: 'manual',
      command: PNPM_COMMAND,
      reason: 'the pinned pnpm setup action installs pnpm 11 and newer, and this project declares pnpm 9'
    });
  });

  it('falls back to manual when pnpm is not declared', () => {
    expect(planInstallStep(pnpmProject({}))).toEqual({
      kind: 'manual',
      command: PNPM_COMMAND,
      reason: PNPM_UNDECLARED
    });
  });

  it('falls back to manual when the pnpm version is unparseable', () => {
    expect(planInstallStep(pnpmProject({ packageManager: 'pnpm@latest' }))).toEqual({
      kind: 'manual',
      command: PNPM_COMMAND,
      reason: PNPM_UNDECLARED
    });
  });

  it('falls back to manual when there is no package.json', () => {
    expect(planInstallStep(io({ '/proj/pnpm-lock.yaml': '' }))).toEqual({
      kind: 'manual',
      command: PNPM_COMMAND,
      reason: PNPM_UNDECLARED
    });
  });

  it('uses the classic yarn flags for a v1 yarn.lock', () => {
    const lock = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n';
    expect(planInstallStep(io({ '/proj/yarn.lock': lock }))).toEqual({
      kind: 'manual',
      command: 'yarn install --frozen-lockfile --ignore-scripts',
      reason: 'this CLI does not pin a setup step for Yarn'
    });
  });

  it('uses the berry yarn flags for any other yarn.lock', () => {
    expect(planInstallStep(io({ '/proj/yarn.lock': '__metadata:\n  version: 8\n' }))).toEqual({
      kind: 'manual',
      command: 'yarn install --immutable --mode=skip-build',
      reason: 'this CLI does not pin a setup step for Yarn'
    });
  });

  it.each(['bun.lock', 'bun.lockb'])('falls back to manual for %s', (file) => {
    expect(planInstallStep(io({ [`/proj/${file}`]: '' }))).toEqual({
      kind: 'manual',
      command: 'bun install --frozen-lockfile --ignore-scripts',
      reason: 'this CLI does not pin a setup step for Bun'
    });
  });

  it('falls back to manual npm ci when there is no lockfile', () => {
    expect(planInstallStep(io({ '/proj/package.json': '{}' }))).toEqual({
      kind: 'manual',
      command: 'npm ci --ignore-scripts',
      reason:
        'no lockfile was found, so the package manager is unknown (commit your lockfile and re-run with --force to generate the step)'
    });
  });

  it.each([
    ['pnpm@12.18.0', 'pnpm'],
    ['pnpm@12.18.0+sha512.abcdef', 'pnpm'],
    ['pnpm@11.0.0', 'pnpm'],
    ['pnpm@10.33.0', 'manual'],
    ['yarn@4.5.0', 'manual'],
    ['pnpm@latest', 'manual']
  ])('reads packageManager %s as %s', (packageManager, kind) => {
    expect(planInstallStep(pnpmProject({ packageManager })).kind).toBe(kind);
  });

  it.each([
    [{ name: 'pnpm', version: '^11.0.0' }, 'pnpm'],
    [{ name: 'pnpm', version: '>=10' }, 'manual'],
    [
      [
        { name: 'npm', version: '11' },
        { name: 'pnpm', version: '12.1.0' }
      ],
      'manual'
    ],
    [{ name: 'npm', version: '11.0.0' }, 'manual']
  ])('reads devEngines.packageManager %j as %s', (packageManager, kind) => {
    expect(planInstallStep(pnpmProject({ devEngines: { packageManager } })).kind).toBe(kind);
  });

  it.each([
    [{ packageManager: 'pnpm@12.0.0', devEngines: { packageManager: [{ name: 'pnpm', version: '12.1.0' }] } }, 'pnpm'],
    [{ packageManager: 'yarn@4.5.0', devEngines: { packageManager: { name: 'pnpm', version: '12.1.0' } } }, 'pnpm'],
    [{ packageManager: 'pnpm@12.0.0', devEngines: { packageManager: { name: 'pnpm', version: '' } } }, 'pnpm']
  ])('reads %j as %s, in the order the pinned setup action reads them', (pkg, kind) => {
    expect(planInstallStep(pnpmProject(pkg)).kind).toBe(kind);
  });

  it('lets devEngines.packageManager decide over packageManager', () => {
    const pkg = { packageManager: 'pnpm@12.0.0', devEngines: { packageManager: { name: 'pnpm', version: '^10' } } };
    expect(planInstallStep(pnpmProject(pkg))).toEqual({
      kind: 'manual',
      command: PNPM_COMMAND,
      reason: 'the pinned pnpm setup action installs pnpm 11 and newer, and this project declares pnpm 10'
    });
  });

  it.each([['pnpm'], [11], [{ name: 'pnpm', version: 11 }]])(
    'does not read a malformed declaration %j as pnpm 11+',
    (value) => {
      expect(planInstallStep(pnpmProject({ packageManager: value })).kind).toBe('manual');
      expect(planInstallStep(pnpmProject({ devEngines: { packageManager: value } })).kind).toBe('manual');
    }
  );

  it('prefers pnpm-lock.yaml over package-lock.json when both exist', () => {
    const plan = planInstallStep(
      io({ '/proj/pnpm-lock.yaml': '', '/proj/package-lock.json': '{}', '/proj/package.json': '{}' })
    );
    expect(plan.kind).toBe('manual');
    expect(plan).toMatchObject({ command: PNPM_COMMAND });
  });

  it('survives a package.json that is not valid JSON', () => {
    expect(planInstallStep(io({ '/proj/pnpm-lock.yaml': '', '/proj/package.json': '{' }))).toEqual({
      kind: 'manual',
      command: PNPM_COMMAND,
      reason: PNPM_UNDECLARED
    });
  });

  it('names the declared major in the reason', () => {
    expect(planInstallStep(pnpmProject({ packageManager: 'pnpm@10.33.0' }))).toMatchObject({
      reason: expect.stringContaining('declares pnpm 10')
    });
  });
});

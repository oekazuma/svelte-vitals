#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveActionPin } from './resolve-action-pin.mjs';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const cliDir = join(scriptsDir, '..');
const outPath = join(cliDir, 'src', 'ci', 'action-pin.generated.ts');

const { sha, version } = await resolveActionPin();
writeFileSync(
  outPath,
  `// Generated by \`pnpm run update-action-pin\` — do not edit by hand.\n` +
    `export const ACTION_SHA = '${sha}';\n` +
    `export const ACTION_VERSION = '${version}';\n`
);
console.log(`Updated action-pin.generated.ts -> svelte-vitals-action@${version} (${sha})`);
